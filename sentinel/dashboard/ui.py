def setup_page(title: str, subtitle: str) -> None:
    st.markdown(CSS, unsafe_allow_html=True)
    st.markdown(
        f'<p class="ss-title">{escape(title)}</p><p class="ss-sub">{escape(subtitle)}</p>',
        unsafe_allow_html=True,
    )


def badge(text: str, key: str | None = None) -> str:
    color = COLORS.get(key or text, "#7B8597")
    return (
        f'<span class="ss-badge" style="color:{color};border-color:{color}55;'
        f'background:{color}1A">{escape(str(text))}</span>'
    )


def card(label: str, value: str | int, sub: str = "", color: str | None = None) -> None:
    style = f' style="color:{color}"' if color else ""
    st.markdown(
        f'<div class="ss-card"><div class="k">{escape(label)}</div>'
        f'<div class="v"{style}>{escape(str(value))}</div>'
        f'<div class="s">{escape(sub)}</div></div>',
        unsafe_allow_html=True,
    )


def demo_notice(record: AnalysisRecord | None = None, text: str | None = None) -> None:
    if record is not None and not record.demo:
        return
    message = text or (
        f"Demonstration data - scenario '{record.demo_scenario}', generated by "
        "running the real pipeline on repository fixtures. Not a production "
        "finding."
        if record
        else ""
    )
    st.markdown(f'<div class="ss-demo">{escape(message)}</div>', unsafe_allow_html=True)


def decision_banner(record: AnalysisRecord) -> None:
    decision = record.decision
    if decision is None:
        return
    color = COLORS[decision.result.value]
    meta = (
        f"{record.name} · policy {decision.policy_name}@{decision.policy_version} · "
        f"evaluated {fmt_ts(decision.evaluated_at)}"
    )
    st.markdown(
        f'<div class="ss-banner" style="border-color:{color}88;background:{color}14">'
        f'<span class="r" style="color:{color}">{escape(decision.result.value)}</span>'
        f'<span class="m">{escape(meta)}</span></div>',
        unsafe_allow_html=True,
    )


def checks_list(checks: list[CheckResult]) -> None:
    rows = []
    for check in checks:
        req = "required" if check.required else "optional"
        mode = f" · {check.evidence_mode.value} evidence" if check.evidence_mode else ""
        rows.append(
            f'<div class="ss-check">{badge(check.status.value)}'
            f'<div><div class="t">{escape(check.title)} '
            f'<span style="color:#7B8597;font-weight:400;font-size:0.8rem">'
            f"({req}{escape(mode)})</span></div>"
            f'<div class="d">{escape(check.summary)}</div></div></div>'
        )
    st.markdown("".join(rows), unsafe_allow_html=True)


def severity_chart(frame: pd.DataFrame, height: int = 220) -> alt.Chart:
    return (
        alt.Chart(frame)
        .mark_bar(cornerRadiusTopRight=3, cornerRadiusBottomRight=3)
        .encode(
            y=alt.Y("severity:N", sort=SEVERITY_ORDER, title=None),
            x=alt.X("count:Q", title="confirmed findings", axis=alt.Axis(tickMinStep=1)),
            color=alt.Color(
                "severity:N",
                scale=alt.Scale(domain=SEVERITY_ORDER, range=SEVERITY_COLORS),
                legend=None,
            ),
            tooltip=["severity", "count"],
        )
        .properties(height=height)
    )


def results_chart(counts: dict[str, int], height: int = 220) -> alt.Chart:
    frame = pd.DataFrame({"result": list(counts), "count": list(counts.values())})
    domain = list(counts)
    return (
        alt.Chart(frame)
        .mark_arc(innerRadius=58, cornerRadius=3)
        .encode(
            theta="count:Q",
            color=alt.Color(
                "result:N",
                scale=alt.Scale(domain=domain, range=[COLORS[d] for d in domain]),
                legend=alt.Legend(orient="right", title=None),
            ),
            tooltip=["result", "count"],
        )
        .properties(height=height)
    )


def record_label(row: dict) -> str:
    result = row.get("result") or "-"
    demo = " [demo]" if row.get("demo") else ""
    return f"{fmt_ts(row['created_at'])} · {row['name']} · {result}{demo}"
