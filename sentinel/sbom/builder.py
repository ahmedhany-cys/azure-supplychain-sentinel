"""Build a validated CycloneDX SBOM and normalised inventory for a project directory."""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from sentinel.config import Settings
from sentinel.core.models import EvidenceMode, Inventory, SBOMInfo
from sentinel.core.runner import run_tool, tool_version, which
from sentinel.core.security import SecurityError, parse_json_bytes, sha256_bytes
from sentinel.sbom import cyclonedx
from sentinel.sbom.discovery import discover, parse_project, project_identities


@dataclass
class SBOMBuild:
    inventory: Inventory
    document: dict[str, Any] | None
    raw: bytes | None
    syft_version: str | None


def run_syft(
    root: Path, settings: Settings, project_name: str
) -> tuple[dict[str, Any] | None, str | None, str | None]:
    """Return (document, syft_version, error)."""
    argv = [
        settings.syft_bin,
        "scan",
        f"dir:{root}",
        "--output",
        "cyclonedx-json",
        "--quiet",
        "--source-name",
        project_name,
        "--exclude",
        "./**/node_modules/**",
        "--exclude",
        "./**/.venv/**",
        "--exclude",
        "./**/.git/**",
    ]
    result = run_tool(
        argv, timeout=settings.syft_timeout, env_extra={"SYFT_CHECK_FOR_APP_UPDATE": "false"}
    )
    version = tool_version(settings.syft_bin, ["version"])
    if not result.ok:
        return (
            None,
            version,
            result.error or f"syft exited {result.returncode}: {result.stderr[:300]}",
        )
    try:
        doc = parse_json_bytes(result.stdout)
    except SecurityError as exc:
        return None, version, f"syft produced unparseable output: {exc}"
    if not isinstance(doc, dict):
        return None, version, "syft output is not a JSON object"
    return doc, version, None


def build_sbom(root: Path, settings: Settings, project_name: str | None = None) -> SBOMBuild:
    root = root.resolve()
    project_name = project_name or root.name
    discovery = discover(root)
    native = parse_project(root, discovery)
    discovery.warnings.extend(native.warnings)

    errors: list[str] = []
    doc: dict[str, Any] | None = None
    mode = EvidenceMode.NATIVE
    syft_version = None
    want_syft = settings.use_syft != "off"
    if want_syft and which(settings.syft_bin):
        doc, syft_version, err = run_syft(root, settings, project_name)
        if err:
            errors.append(
                f"Syft SBOM generation failed: {err}; fell back to native lockfile parsing"
            )
        else:
            mode = EvidenceMode.LIVE
            doc = cyclonedx.strip_local_paths(doc, str(root))
            adopted = cyclonedx.adopt_root_component(
                doc, project_identities(root, discovery), project_name
            )
            if adopted:
                discovery.warnings.append(
                    f"{adopted} is the project itself; recorded as the SBOM subject, "
                    "not as a dependency"
                )
            enriched = cyclonedx.enrich(doc, native.components)
            if native.components and enriched < len(native.components):
                discovery.warnings.append(
                    f"{len(native.components) - enriched} natively parsed packages were not "
                    "matched in the Syft SBOM"
                )
    elif want_syft:
        discovery.warnings.append("Syft is not installed; SBOM generated by the native parser")

    if doc is None:
        doc = cyclonedx.build_native(native.components, project_name)

    raw = json.dumps(doc, indent=2, sort_keys=False).encode()
    validation = cyclonedx.validate(raw)
    info: SBOMInfo = cyclonedx.describe(doc)
    info.mode = mode
    info.sha256 = sha256_bytes(raw)
    info.validation = validation
    info.errors = errors
    components = cyclonedx.parse_components(doc)
    return SBOMBuild(
        inventory=Inventory(components=components, sbom=info, discovery=discovery),
        document=doc,
        raw=raw,
        syft_version=syft_version,
    )


def load_sbom(raw: bytes, label: str = "uploaded SBOM") -> SBOMBuild:
    """Normalise an existing CycloneDX SBOM (baseline or uploaded)."""
    validation = cyclonedx.validate(raw)
    try:
        doc = parse_json_bytes(raw)
    except SecurityError as exc:
        info = SBOMInfo(validation=validation, errors=[f"{label}: {exc}"])
        return SBOMBuild(Inventory(sbom=info), None, raw, None)
    if not isinstance(doc, dict):
        info = SBOMInfo(validation=validation, errors=[f"{label}: not a JSON object"])
        return SBOMBuild(Inventory(sbom=info), None, raw, None)
    info = cyclonedx.describe(doc)
    info.mode = EvidenceMode.RECORDED
    info.sha256 = sha256_bytes(raw)
    info.validation = validation
    return SBOMBuild(
        Inventory(components=cyclonedx.parse_components(doc), sbom=info), doc, raw, None
    )
